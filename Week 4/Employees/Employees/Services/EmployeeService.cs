using Employees.Data;
using Employees.Interfaces;
using Employees.Models;
using Microsoft.EntityFrameworkCore;
using System.Text.Json;
using Employees.DTO;

namespace Employees.Services
{
    public class EmployeeService : IEmployeeService
    {
        private readonly AppDbContext _context;
        private readonly ILogger<EmployeeService> _logger;
        public EmployeeService(AppDbContext context, ILogger<EmployeeService> logger)
        {
            _context = context;
            _logger = logger;
        }
        public async Task<List<EmployeeResponseDto>> GetAllAsync()
        {
            _logger.LogInformation("Fetching All EMployess........");
            var Employees= await _context.Employees
                .AsNoTracking()
                .Select(e => new EmployeeResponseDto
                {
                    EmployeeId = e.EmployeeId,
                    FullName = e.FullName,
                    Email = e.Email,
                    Phone = e.Phone,
                    DateOfJoining = e.DateOfJoining,
                    Salary = e.Salary,
                    DepartmentId = e.DepartmentId,
                    DepartmentName = e.Department!.DepartmentName,
                    Role = e.Role,
                    IsActive = e.IsActive
                })
                .ToListAsync();
            _logger.LogInformation($"total Employee {Employees.Count} is Available");
            return Employees;
        }
        public async Task<EmployeeResponseDto?> GetByIdAsync(int id)
        {
            _logger.LogInformation("Fectching Employeed ById................");
            var Employees= await _context.Employees
                .AsNoTracking()
                .Where(e => e.EmployeeId == id)
                .Select(e => new EmployeeResponseDto
                {
                    EmployeeId = e.EmployeeId,
                    FullName = e.FullName,
                    Email = e.Email,
                    Phone = e.Phone,
                    DateOfJoining = e.DateOfJoining,
                    Salary = e.Salary,
                    DepartmentId = e.DepartmentId,
                    DepartmentName = e.Department!.DepartmentName,
                    Role = e.Role,
                    IsActive = e.IsActive
                })
                .FirstOrDefaultAsync();
            if (Employees == null)
            {
                _logger.LogWarning("Employee with ID {EmployeeId} not found.", id);
                return null;
            }

            _logger.LogInformation(
                "Employee {EmployeeId} fetched successfully.", id);

            return Employees;
        }
        public async Task<EmployeeResponseDto> CreateAsync( InsertEmployeeDto dto)
        {
            await using var transaction =
                await _context.Database.BeginTransactionAsync();

            _logger.LogInformation("Creating employee...");

            // Step 1: Convert DTO to Employee entity
            var employee = new Employee
            {
                FullName = dto.FullName,
                Email = dto.Email,
                Phone = dto.Phone,
                DateOfJoining = dto.DateOfJoining,
                Salary = dto.Salary,
                DepartmentId = dto.DepartmentId,
                Role = dto.Role,
                IsActive = dto.IsActive
            };

            // Step 2: Save Employee
            _context.Employees.Add(employee);
            await _context.SaveChangesAsync();

            // EmployeeId is now generated by SQL Server

            // Step 3: Create audit log
            var auditLog = new EmployeeAuditLog
            {
                EmployeeId = employee.EmployeeId,
                Action = "CREATE",
                OldValues = null,
                NewValues = JsonSerializer.Serialize(new
                {
                    employee.FullName,
                    employee.Email,
                    employee.Phone,
                    employee.DateOfJoining,
                    employee.Salary,
                    employee.DepartmentId,
                    employee.Role,
                    employee.IsActive
                }),
                ChangedBy = "System",
                ChangedAt = DateTime.UtcNow
            };

            _context.EmployeeAuditLogs.Add(auditLog);
            await _context.SaveChangesAsync();

            // Step 4: Commit transaction
            await transaction.CommitAsync();

            _logger.LogInformation(
                "Employee {EmployeeId} created successfully.",
                employee.EmployeeId);

            // Step 5: Return Response DTO
            return new EmployeeResponseDto
            {
                EmployeeId = employee.EmployeeId,
                FullName = employee.FullName,
                Email = employee.Email,
                Phone = employee.Phone,
                DateOfJoining = employee.DateOfJoining,
                Salary = employee.Salary,
                DepartmentId = employee.DepartmentId,
                DepartmentName = await _context.Departments
                    .Where(d => d.DepartmentId == employee.DepartmentId)
                    .Select(d => d.DepartmentName)
                    .FirstOrDefaultAsync(),
                Role = employee.Role,
                IsActive = employee.IsActive
            };
        }
        public async Task<bool> UpdateAsync(int id, UpdateEmployeeDto employee)
        {
            
            _logger.LogInformation("Updating Employee...");

            var existingEmployee = await _context.Employees
                .FirstOrDefaultAsync(e => e.EmployeeId == id);

            if (existingEmployee == null)
            {
                _logger.LogWarning("Employee {EmployeeId} not found.", id);
                return false;
            }

            await using var transaction =
                await _context.Database.BeginTransactionAsync();

            var oldValues = JsonSerializer.Serialize(new
            {
                existingEmployee.FullName,
                existingEmployee.Email,
                existingEmployee.Phone,
                existingEmployee.DateOfJoining,
                existingEmployee.Salary,
                existingEmployee.DepartmentId,
                existingEmployee.IsActive,
                existingEmployee.Role,
            });

            existingEmployee.FullName = employee.FullName;
            existingEmployee.Email = employee.Email;
            existingEmployee.Phone = employee.Phone;
            existingEmployee.DateOfJoining = employee.DateOfJoining;
            existingEmployee.Salary = employee.Salary;
            existingEmployee.DepartmentId = employee.DepartmentId;
            existingEmployee.Role = employee.Role;
            existingEmployee.IsActive = employee.IsActive;

            var newValues = JsonSerializer.Serialize(new
            {
                existingEmployee.FullName,
                existingEmployee.Email,
                existingEmployee.Phone,
                existingEmployee.DateOfJoining,
                existingEmployee.Salary,
                existingEmployee.DepartmentId,
                existingEmployee.IsActive,
                existingEmployee.Role,
            });

            var auditLog = new EmployeeAuditLog
            {
                EmployeeId = id,
                Action = "UPDATE",
                OldValues = oldValues,
                NewValues = newValues,
                ChangedBy = "System",
                ChangedAt = DateTime.UtcNow
            };

            _context.EmployeeAuditLogs.Add(auditLog);

            await _context.SaveChangesAsync();

            await transaction.CommitAsync();

            _logger.LogInformation(
                "Employee {EmployeeId} updated and audit logged.",
                id);

            return true;
        }

        public async Task<bool> DeleteAsync(int id)
        {
            var employee = await _context.Employees.FindAsync(id);

            if (employee == null)
            {
                _logger.LogWarning(
                    "Employee {EmployeeId} not found.", id);
                return false;
            }

            await using var transaction =
                await _context.Database.BeginTransactionAsync();

            var oldValues = JsonSerializer.Serialize(new
            {
                employee.FullName,
                employee.Email,
                employee.Phone,
                employee.DateOfJoining,
                employee.Salary,
                employee.DepartmentId,
                employee.Role,
                employee.IsActive
            });

            var auditLog = new EmployeeAuditLog
            {
                EmployeeId = id,
                Action = "DELETE",
                OldValues = oldValues,
                NewValues = null,
                ChangedBy = "System",
                ChangedAt = DateTime.UtcNow
            };

            _context.EmployeeAuditLogs.Add(auditLog);
            _context.Employees.Remove(employee);

            await _context.SaveChangesAsync();
            await transaction.CommitAsync();

            _logger.LogInformation(
                "Employee {EmployeeId} deleted and audit logged.", id);

            return true;
        }

        public async Task<List<EmployeeResponseDto>> SearchByNameAsync(string name)
        {
            if (string.IsNullOrWhiteSpace(name))
            {
                return new List<EmployeeResponseDto>();
            }
            return await _context.Employees
            .AsNoTracking()
            .Where(e => e.FullName.Contains(name))
            .Select(e => new EmployeeResponseDto
            {
                EmployeeId = e.EmployeeId,
                FullName = e.FullName,
                Email = e.Email,
                Phone = e.Phone,
                DateOfJoining = e.DateOfJoining,
                Salary = e.Salary,
                DepartmentId = e.DepartmentId,
                DepartmentName = e.Department!.DepartmentName,
                Role = e.Role,
                IsActive = e.IsActive
            })
            .ToListAsync();
        }
    }
}
